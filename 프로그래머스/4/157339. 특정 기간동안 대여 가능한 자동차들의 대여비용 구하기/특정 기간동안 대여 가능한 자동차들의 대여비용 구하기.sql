# type 세단 또는 SUV -> CAR_RENTAL_COMPANY_CAR
# 2022.11.1 ~ 222.11.30까지 대여 가능 -> CAR_RENTAL_COMPANY_RENTAL_HISTORY 이미 대여된 자동차 제외
# 30일간의 대여 금액이 50만원이상 200만원 미만
# 자동차 아이디, 종류, 대여금액(FEE)
# FEE DESC, TYPE ASC, ID DESC
SELECT 
    C.CAR_ID, 
    C.CAR_TYPE, 
    ROUND(C.DAILY_FEE* 30 * (100-D.DISCOUNT_RATE) / 100) AS FEE
FROM CAR_RENTAL_COMPANY_CAR C
JOIN CAR_RENTAL_COMPANY_DISCOUNT_PLAN D
ON C.CAR_TYPE = D.CAR_TYPE
WHERE C.CAR_TYPE IN ('세단', 'SUV')
    AND D.DURATION_TYPE = '30일 이상'
    AND C.CAR_ID NOT IN (
        SELECT CAR_ID
        FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY
        WHERE START_DATE <= '2022-11-30' AND END_DATE >= '2022-11-01'
    )
AND ROUND(C.DAILY_FEE* 30 * (100-D.DISCOUNT_RATE) / 100) >= 500000
AND ROUND(C.DAILY_FEE* 30 * (100-D.DISCOUNT_RATE) / 100) < 2000000
ORDER BY FEE DESC, C.CAR_TYPE ASC, C.CAR_ID DESC